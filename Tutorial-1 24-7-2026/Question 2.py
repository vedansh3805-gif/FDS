import numpy as np

print("Array of 10 zeros:")
print(np.zeros(10))

print("\nArray of 8 ones:")
print(np.ones(8))

print("\nArray containing values from 1 to 20:")
print(np.arange(1, 21))

print("\nFive equally spaced numbers between 10 and 50:")
print(np.linspace(10, 50, 5))

print("\n4 × 4 Identity Matrix:")
print(np.identity(4))